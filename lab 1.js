// Завдання 1: Перестановка значень змінних (варіант ACDBE)
function переставитиЗначення() {
    let A = 1, B = 2, C = 3, D = 4, E = 5;

    let tempA = A;
    let tempB = B;
    let tempC = C;
    let tempD = D;

    A = C;
    B = D;
    C = tempB;
    D = tempA;
    E = E;

    console.log(`Завдання 1: Перестановка змінних`);
    console.log(`Нові значення: A=${A}, B=${B}, C=${C}, D=${D}, E=${E}`);
}

// Завдання 2: Обчислення параметрів фігур
function обчислитиПараметрФігури() {
    console.log("\nЗавдання 2: Обчислення периметра фігур");

    // Трикутник із заданими координатами
    let x1 = 0, y1 = 0;
    let x2 = 3, y2 = 0;
    let x3 = 0, y3 = 4;

    let сторона1 = Math.sqrt((x2 - x1) ** 2 + (y2 - y1) ** 2);
    let сторона2 = Math.sqrt((x3 - x2) ** 2 + (y3 - y2) ** 2);
    let сторона3 = Math.sqrt((x3 - x1) ** 2 + (y3 - y1) ** 2);
    let периметрТрикутника = сторона1 + сторона2 + сторона3;

    console.log(`Периметр трикутника: ${периметрТрикутника.toFixed(2)}`);

    // Прямокутник (ширина = 5, висота = 3)
    let ширина = 5, висота = 3;
    let периметрПрямокутника = 2 * (ширина + висота);

    console.log(`Периметр прямокутника: ${периметрПрямокутника}`);
}

// Завдання 3: Чи належить точка фігурі
function перевіритиПеретин() {
    console.log("\nЗавдання 3: Перевірка точки");

    // Прямокутник (ліва верхня точка 2,2, права нижня 6,6)
    let x1 = 2, y1 = 6;
    let x2 = 6, y2 = 2;

    // Задана точка (4,4)
    let x = 4, y = 4;

    let перетинає = x >= x1 && x <= x2 && y >= y2 && y <= y1;
    console.log(`Точка (${x}, ${y}) ${перетинає ? "знаходиться" : "не знаходиться"} всередині прямокутника`);
}

// Виконання функцій
переставитиЗначення();
обчислитиПараметрФігури();
перевіритиПеретин();